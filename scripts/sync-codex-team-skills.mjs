import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const markerPrefix = '<!-- Generated by scripts/sync-codex-team-skills.mjs from .claude/skills/';

function ParseMetadata(source, name) {
  const lines = source.replaceAll('\r\n', '\n').split('\n');
  const end = lines.indexOf('---', 1);
  if (lines[0] !== '---' || end < 0) throw new Error(`${name}: missing frontmatter delimiters.`);
  const metadata = {};
  for (const line of lines.slice(1, end)) {
    if (!line.trim() || line.startsWith('#')) continue;
    const match = line.match(/^([a-z][a-z-]*): (.+)$/);
    if (!match || Object.hasOwn(metadata, match[1])) throw new Error(`${name}: unsupported or duplicate frontmatter: ${line}`);
    metadata[match[1]] = match[2].trim();
  }
  const ReadString = key => {
    const value = metadata[key];
    if (!value) throw new Error(`${name}: missing ${key} metadata.`);
    if (value.startsWith('"')) {
      try { return JSON.parse(value); } catch { throw new Error(`${name}: unsupported ${key} double-quoted metadata.`); }
    }
    if (/^[\[\]{}'|>&*!]/.test(value) || /:\s|\s#/.test(value)) throw new Error(`${name}: unsupported ${key} metadata.`);
    return value;
  };
  const skillName = ReadString('name');
  if (skillName !== name) throw new Error(`${name}: frontmatter name must equal folder name.`);
  const description = ReadString('description');
  const argumentHint = Object.hasOwn(metadata, 'argument-hint') ? ReadString('argument-hint') : null;
  const disabled = metadata['disable-model-invocation'];
  if (disabled !== undefined && disabled !== 'true' && disabled !== 'false') {
    throw new Error(`${name}: disable-model-invocation metadata must be true or false.`);
  }
  return { description, argumentHint, disabled: disabled === 'true' };
}

function RenderAdapter(name, metadata) {
  const suffix = ' (RehabTrainerHub game team skill)';
  const limit = Math.min(1000, 1024 - suffix.length);
  let description = metadata.description.replace(/\s+/g, ' ').trim();
  if (description.length > limit) {
    const prefix = description.slice(0, limit - 3);
    const boundary = description[limit - 3] === ' ' ? prefix.length : prefix.lastIndexOf(' ');
    description = `${prefix.slice(0, Math.max(0, boundary)).trimEnd()}...`;
  }
  const sourcePath = `.claude/skills/${name}/SKILL.md`;
  let instruction = `Read \`${sourcePath}\` and follow it, with \`.claude/docs/rehab-game-team.md\` and \`AGENTS.md\` (AGENTS.md wins on conflict).`;
  if (metadata.argumentHint) instruction += ` Arguments: ${metadata.argumentHint.replace(/\s+/g, ' ')}.`;
  if (metadata.disabled) instruction += ' Use this skill only when the user asks for it by name.';
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description + suffix)}`,
    '---',
    `${markerPrefix}${name}/SKILL.md. Do not edit by hand; run npm run sync:team-skills. -->`,
    '',
    `# ${name} (game team skill, Codex adapter)`,
    '',
    instruction,
    '',
    'The skill was written for Claude Code. In Codex:',
    '- Questions (`AskUserQuestion`, "ask the user", "May I write"): in an interactive session ask in plain text and wait for the answer; as a non-interactive Codex worker put the question and any draft in your report and stop.',
    '- A line made of `!` and a backticked command is run before the skill is read: run that command yourself from the repo root and use its output. `${CLAUDE_SKILL_DIR}` means `.claude/skills/' + name + '`. `$ARGUMENTS` means the arguments the user gave.',
    '- `allowed-tools` is not enforced here; treat it as the skill\'s intended scope.',
    '- Team members ("run `<agent>` as a Codex worker", `.claude/scripts/codex-agent.sh`): take each role yourself by reading `.claude/agents/<agent>.md`, one role at a time, and label each phase\'s output with the role. Do not call `codex-agent.sh` from Codex.',
    '- `TaskCreate` / `TaskUpdate` / `TaskList`: keep a plain checklist in your reply instead.',
    '- Do not commit, push, deploy or publish unless the user asks.',
    '',
  ].join('\n');
}

function Sync(root, check) {
  const sourceRoot = resolve(root, '.claude/skills');
  const adapterRoot = resolve(root, '.agents/skills');
  const expected = new Map();
  for (const entry of readdirSync(sourceRoot, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const sourcePath = resolve(sourceRoot, entry.name, 'SKILL.md');
    if (!entry.isDirectory() || !existsSync(sourcePath)) continue;
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.name)) throw new Error(`${entry.name}: unsupported skill folder name.`);
    expected.set(entry.name, RenderAdapter(entry.name, ParseMetadata(readFileSync(sourcePath, 'utf8'), entry.name)));
  }
  const problems = [];
  const writes = [];
  const orphans = [];
  for (const [name, content] of expected) {
    const path = resolve(adapterRoot, name, 'SKILL.md');
    const existing = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (existing === content) continue;
    if (!check && existing !== null && !existing.includes(markerPrefix)) throw new Error(`Refusing to overwrite unmarked adapter: ${name}`);
    problems.push(`${existing === null ? 'missing' : 'stale'} adapter: ${name}`);
    writes.push({ name, path, content });
  }
  if (existsSync(adapterRoot)) {
    for (const entry of readdirSync(adapterRoot, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const path = resolve(adapterRoot, entry.name, 'SKILL.md');
      if (!entry.isDirectory() || expected.has(entry.name) || !existsSync(path)) continue;
      if (!readFileSync(path, 'utf8').includes(markerPrefix)) continue;
      problems.push(`orphaned adapter: ${entry.name}`);
      orphans.push(resolve(adapterRoot, entry.name));
    }
  }
  if (check) {
    if (problems.length) {
      console.error(`${problems.join('\n')}\nRun npm run sync:team-skills.`);
      process.exitCode = 1;
    } else console.log(`Codex team skill adapters are current (${expected.size}).`);
    return;
  }
  for (const { name, path, content } of writes) {
    mkdirSync(resolve(adapterRoot, name), { recursive: true });
    writeFileSync(path, content, 'utf8');
  }
  for (const path of orphans) rmSync(path, { recursive: true, force: true });
  console.log(`Synced ${expected.size} Codex team skill adapters (${writes.length} updated, ${orphans.length} orphaned folders removed).`);
}

try {
  let root = resolve(import.meta.dirname, '..');
  let check = false;
  const args = process.argv.slice(2);
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--check') check = true;
    else if (args[index] === '--root' && args[index + 1] && !args[index + 1].startsWith('--')) root = resolve(args[++index]);
    else throw new Error(`Unknown or incomplete argument: ${args[index]}. Usage: node scripts/sync-codex-team-skills.mjs [--check] [--root <dir>]`);
  }
  Sync(root, check);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
