import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import test from 'node:test';

const repoRoot = resolve(import.meta.dirname, '..');
const script = resolve(repoRoot, 'scripts/sync-codex-team-skills.mjs');
const marker = '<!-- Generated by scripts/sync-codex-team-skills.mjs from .claude/skills/';

function Run(root, ...args) {
  const result = spawnSync(process.execPath, [script, '--root', root, ...args], { encoding: 'utf8' });
  assert.ifError(result.error);
  return { ...result, output: result.stdout + result.stderr };
}

function Fixture(t) {
  const root = mkdtempSync(resolve(tmpdir(), 'team-skills-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return root;
}

function Write(root, path, text) {
  const target = resolve(root, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text, 'utf8');
}

function Skill(root, name, frontmatter = 'description: Review the game.') {
  Write(root, `.claude/skills/${name}/SKILL.md`, `---\nname: ${name}\n${frontmatter}\n---\n\n# Source skill\n`);
}

function Adapter(root, name) {
  return readFileSync(resolve(root, `.agents/skills/${name}/SKILL.md`), 'utf8');
}

function Header(source) {
  const match = source.match(/^---\nname: ([^\n]+)\ndescription: ("[^\n]*")\n---\n/);
  assert.ok(match, 'Adapter has a one-line YAML description.');
  return { name: match[1], description: JSON.parse(match[2]) };
}

test('all repository team skills have current Codex adapters with valid metadata', () => {
  const checked = Run(repoRoot, '--check');
  assert.equal(checked.status, 0, checked.output);
  const sourceNames = readdirSync(resolve(repoRoot, '.claude/skills'), { withFileTypes: true })
    .filter(entry => entry.isDirectory() && existsSync(resolve(repoRoot, `.claude/skills/${entry.name}/SKILL.md`)))
    .map(entry => entry.name).sort();
  const generatedNames = readdirSync(resolve(repoRoot, '.agents/skills'), { withFileTypes: true })
    .filter(entry => entry.isDirectory() && existsSync(resolve(repoRoot, `.agents/skills/${entry.name}/SKILL.md`)))
    .filter(entry => Adapter(repoRoot, entry.name).includes(marker)).map(entry => entry.name).sort();
  assert.deepEqual(generatedNames, sourceNames);
  for (const name of sourceNames) {
    const source = Adapter(repoRoot, name);
    const header = Header(source);
    assert.equal(header.name, name);
    assert.ok(header.description.length <= 1024);
    assert.doesNotMatch(header.description, /[\r\n]/);
    assert.doesNotMatch(source, /\r/);
    assert.ok(source.includes(`Read \`.claude/skills/${name}/SKILL.md\``));
    assert.match(source, /Do not call `codex-agent\.sh` from Codex/);
  }
});

test('check lists missing, stale and orphaned adapters without writing; sync preserves unmarked skills', t => {
  const root = Fixture(t);
  Skill(root, 'alpha');
  const missing = Run(root, '--check');
  assert.equal(missing.status, 1, missing.output);
  assert.match(missing.output, /missing.*alpha/i);
  assert.equal(existsSync(resolve(root, '.agents')), false);
  assert.equal(Run(root).status, 0);
  const original = Adapter(root, 'alpha');
  Skill(root, 'alpha', 'description: Changed review.');
  Skill(root, 'beta');
  Write(root, '.agents/skills/orphan/SKILL.md', original.replaceAll('alpha', 'orphan'));
  Write(root, '.agents/skills/manual/SKILL.md', '# Hand-authored skill\n');
  Write(root, '.agents/skills/manual/notes.txt', 'keep');
  Write(root, '.agents/skills/no-skill/notes.txt', 'keep');
  const checked = Run(root, '--check');
  assert.equal(checked.status, 1, checked.output);
  assert.match(checked.output, /missing.*beta/i);
  assert.match(checked.output, /stale.*alpha/i);
  assert.match(checked.output, /orphaned.*orphan/i);
  assert.equal(Adapter(root, 'alpha'), original);
  assert.equal(existsSync(resolve(root, '.agents/skills/beta')), false);
  assert.ok(existsSync(resolve(root, '.agents/skills/orphan/SKILL.md')));
  const synced = Run(root);
  assert.equal(synced.status, 0, synced.output);
  assert.equal(existsSync(resolve(root, '.agents/skills/orphan')), false);
  assert.equal(Adapter(root, 'manual'), '# Hand-authored skill\n');
  assert.equal(readFileSync(resolve(root, '.agents/skills/manual/notes.txt'), 'utf8'), 'keep');
  assert.equal(readFileSync(resolve(root, '.agents/skills/no-skill/notes.txt'), 'utf8'), 'keep');
  assert.equal(Run(root, '--check').status, 0);
  const before = Adapter(root, 'alpha');
  assert.equal(Run(root).status, 0);
  assert.equal(Adapter(root, 'alpha'), before);
});

test('adapters normalize and escape metadata, truncate at a word boundary and retain invocation rules', t => {
  const root = Fixture(t);
  const description = 'Review "controls" \\ input\n' + 'longword '.repeat(180);
  Skill(root, 'alpha', `description: ${JSON.stringify(description)}\nargument-hint: "[game id]"\ndisable-model-invocation: true`);
  const synced = Run(root);
  assert.equal(synced.status, 0, synced.output);
  const source = Adapter(root, 'alpha');
  const header = Header(source);
  assert.ok(header.description.startsWith('Review "controls" \\ input longword'));
  assert.ok(header.description.length <= 1024);
  assert.match(header.description, /longword\.\.\. \(RehabTrainerHub game team skill\)$/);
  assert.match(source, /Arguments: \[game id\]\./);
  assert.match(source, /Use this skill only when the user asks for it by name\./);
  assert.ok(source.includes('${CLAUDE_SKILL_DIR}'));
  assert.ok(source.includes('`$ARGUMENTS`'));
});

test('sync rejects unsupported metadata and refuses to overwrite an unmarked skill', t => {
  const root = Fixture(t);
  for (const frontmatter of [
    'description: >\n  Multiline YAML.',
    'description: "bad\\q"',
    'description: Review.\nname: other',
    'description: Review.\ndisable-model-invocation: yes',
    "description: 'Unsupported single quotes.'",
  ]) {
    Skill(root, 'alpha', frontmatter);
    const result = Run(root);
    assert.equal(result.status, 1, result.output);
    assert.match(result.output, /alpha.*(frontmatter|metadata|name|description|disable-model-invocation)/i);
  }
  Write(root, '.claude/skills/alpha/SKILL.md', '---\nname: other\ndescription: Review.\n---\n');
  assert.match(Run(root).output, /name.*folder/i);
  Skill(root, 'alpha');
  Write(root, '.agents/skills/alpha/SKILL.md', '# Keep this manual skill\n');
  const collision = Run(root);
  assert.equal(collision.status, 1, collision.output);
  assert.match(collision.output, /unmarked.*alpha/i);
  assert.equal(Adapter(root, 'alpha'), '# Keep this manual skill\n');
  Skill(root, 'beta');
  const checked = Run(root, '--check');
  assert.equal(checked.status, 1, checked.output);
  assert.match(checked.output, /stale.*alpha/i);
  assert.match(checked.output, /missing.*beta/i);
});
