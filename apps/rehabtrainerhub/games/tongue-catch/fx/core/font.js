function Build(table, h) {
    const out = {};
    for (const [ch, src] of Object.entries(table)) {
        const rows = src.split("|");
        out[ch] = { w: rows[0].length, rows: rows.map((r) => [...r].map((c) => c === "#")) };
        if (rows.length !== h)
            throw new Error(`glyph ${ch} has ${rows.length} rows, expected ${h}`);
    }
    return out;
}
export const pixelFONTS = {
    mini: { h: 5, space: 2, gap: 1, glyphs: Build(pixelMINI, 5) },
    big: { h: 7, space: 3, gap: 1, glyphs: Build(pixelBIG, 7) },
};
/** Width in font pixels of a string (before scaling). */
export function TextWidth(str, font = "mini") {
    const pixelF = pixelFONTS[font];
    let w = 0;
    for (const ch of String(str)) {
        const g = pixelF.glyphs[ch] ?? pixelF.glyphs[ch.toUpperCase()];
        w += (g ? g.w : pixelF.space) + pixelF.gap;
    }
    return Math.max(0, w - pixelF.gap);
}
/** Calls plot(x, y) for every inked font pixel of str, with the top-left of the text at (0, 0). */
export function RasterText(str, font, plot) {
    const pixelF = pixelFONTS[font];
    let x = 0;
    for (const ch of String(str)) {
        const g = pixelF.glyphs[ch] ?? pixelF.glyphs[ch.toUpperCase()];
        if (!g) {
            x += pixelF.space + pixelF.gap;
            continue;
        }
        for (let r = 0; r < pixelF.h; r++)
            for (let c = 0; c < g.w; c++)
                if (g.rows[r][c])
                    plot(x + c, r);
        x += g.w + pixelF.gap;
    }
}
