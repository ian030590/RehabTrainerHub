function Build(table, h) {
  const out = {};
  for (const [ch, src] of Object.entries(table)) {
    const rows = src.split("|");
    out[ch] = { w: rows[0].length, rows: rows.map((r) => [...r].map((c) => c === "#")) };
    if (rows.length !== h) throw new Error(`glyph ${ch} has ${rows.length} rows, expected ${h}`);
  }
  return out;
}

export const fxFONTS = {
  mini: { h: 5, space: 2, gap: 1, glyphs: Build(fxMINI, 5) },
  big: { h: 7, space: 3, gap: 1, glyphs: Build(fxBIG, 7) },
};

/** Width in font pixels of a string (before scaling). */
export function TextWidth(str, font = "mini") {
  const fxF = fxFONTS[font];
  let w = 0;
  for (const ch of String(str)) {
    const g = fxF.glyphs[ch] ?? fxF.glyphs[ch.toUpperCase()];
    w += (g ? g.w : fxF.space) + fxF.gap;
  }
  return Math.max(0, w - fxF.gap);
}

/** Calls plot(x, y) for every inked font pixel of str, with the top-left of the text at (0, 0). */
export function RasterText(str, font, plot) {
  const fxF = fxFONTS[font];
  let x = 0;
  for (const ch of String(str)) {
    const g = fxF.glyphs[ch] ?? fxF.glyphs[ch.toUpperCase()];
    if (!g) {
      x += fxF.space + fxF.gap;
      continue;
    }
    for (let r = 0; r < fxF.h; r++) for (let c = 0; c < g.w; c++) if (g.rows[r][c]) plot(x + c, r);
    x += g.w + fxF.gap;
  }
}
